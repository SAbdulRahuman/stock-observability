#!/usr/bin/env python3
"""Reference implementation of the NSE KPI formulas (stdlib only).

Generates promtool unit tests (prometheus/tests/reference_<family>_test.yml) whose expected
values are computed here from textbook definitions, independently of the PromQL rules.
Each check asserts |rule - reference| <= tol with `abs(rule - E) <= bool tol`, so the file
needs no fuzzy compare and failures show up as value 0.

    python3 prometheus/tests/reference/kpiref.py            # rewrite the test files
    python3 prometheus/tests/reference/kpiref.py --out DIR  # write elsewhere (make check-reference)
"""

import argparse
import math
import os
import random

LOOKBACK = 300  # Prometheus default lookback delta, seconds
REL_TOL = 1e-9  # proposal §A12: exact KPIs within 1e-9 relative
ABS_TOL = 1e-9

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS_DIR = os.path.dirname(HERE)

CORE = {"job": "stock_core", "instance": "se"}
BROAD = {"job": "stock_broad", "instance": "se"}


def instrument(symbol, sector="IT", itype="EQ", tier="core"):
    base = CORE if tier == "core" else BROAD
    return dict(base, exchange="NSE", symbol=symbol, sector=sector, instrument_type=itype, tier=tier)


class Series:
    """A promtool input series: samples at i * step seconds, None = no sample."""

    def __init__(self, metric, labels, step, values, fmt="%.2f"):
        self.metric = metric
        self.labels = labels
        self.step = step
        # Round-trip through the text form so the reference sees exactly what promtool loads.
        self.text = [("_" if v is None else fmt % v) for v in values]
        self.values = [None if s == "_" else float(s) for s in self.text]

    def at(self, t):
        """Instant value at t: newest sample in (t - lookback, t]."""
        i = min(int(t // self.step), len(self.values) - 1)
        while i >= 0 and i * self.step > t - LOOKBACK:
            if self.values[i] is not None:
                return self.values[i]
            i -= 1
        return None

    def samples(self, start, end):
        """Raw samples with timestamps in (start, end]."""
        return [
            (i * self.step, v)
            for i, v in enumerate(self.values)
            if v is not None and start < i * self.step <= end
        ]

    def bars(self, t, rng, res=60):
        """Subquery points of `x[rng:res]` at t: x at every multiple of res in (t - rng, t]."""
        first = (int((t - rng) // res) + 1) * res
        return [self.at(ts) for ts in range(first, int(t) + 1, res)]


def selector(metric, labels):
    return metric + "{" + ",".join('%s="%s"' % (k, v) for k, v in labels.items()) + "}"


def duration(seconds):
    seconds = int(seconds)
    if seconds % 86400 == 0:
        return "%dd" % (seconds // 86400)
    if seconds % 3600 == 0:
        return "%dh" % (seconds // 3600)
    if seconds % 60 == 0:
        return "%dm" % (seconds // 60)
    return "%ds" % seconds


class Check:
    def __init__(self, metric, labels, t, expected, rel_tol=REL_TOL, abs_tol=ABS_TOL):
        self.metric, self.labels, self.t, self.expected = metric, labels, t, expected
        self.tol = max(rel_tol * abs(expected), abs_tol)


class Absent:
    """Asserts that `metric{labels}` has no sample at t."""

    def __init__(self, metric, labels, t):
        self.metric, self.labels, self.t = metric, labels, t


def test_case(name, step, series, checks):
    return {"name": name, "step": step, "series": series, "checks": checks}


def render(family, rule_files, cases, eval_interval):
    out = [
        "# Generated by prometheus/tests/reference/kpiref.py (family %s). DO NOT EDIT." % family,
        "rule_files:",
    ]
    out += ["  - ../rules/%s" % f for f in rule_files]
    out += ["", "evaluation_interval: %s" % duration(eval_interval), "", "tests:"]
    for c in cases:
        out.append("  - name: %s" % c["name"])
        out.append("    interval: %s" % duration(c["step"]))
        out.append("    input_series:")
        for s in c["series"]:
            out.append("      - series: '%s'" % selector(s.metric, s.labels))
            out.append("        values: '%s'" % " ".join(s.text))
        out.append("    promql_expr_test:")
        for ck in c["checks"]:
            sel = selector(ck.metric, ck.labels)
            out.append("      - eval_time: %s" % duration(ck.t))
            if isinstance(ck, Absent):
                out.append("        expr: '%s'" % sel)
                out.append("        exp_samples: []")
                continue
            out.append("        expr: 'abs(%s - (%r)) <= bool %r'" % (sel, ck.expected, ck.tol))
            out.append("        exp_samples:")
            out.append("          - labels: '%s'" % selector("", ck.labels))
            out.append("            value: 1")
    return "\n".join(out) + "\n"


# --- deterministic input data ----------------------------------------------------------------


def random_walk(seed, n, start=100.0, sigma=0.004, tick=0.05):
    rnd = random.Random(seed)
    p, out = start, []
    for _ in range(n):
        p *= math.exp(rnd.gauss(0, sigma))
        out.append(round(round(p / tick) * tick, 2))
    return out


def constant(v, n):
    return [v] * n


# --- base rules (stock_recording.rules.yml) -----------------------------------------------------


def family_base():
    n = 31  # 30 minutes of 1m samples
    infy = instrument("INFY")
    price = Series("stock_last_price", infy, 60, random_walk(1, n))
    opn = Series("stock_open_price", infy, 60, constant(price.values[0], n))
    pc = Series("stock_previous_close_price", infy, 60, constant(98.4, n))
    vwap = Series("stock_average_traded_price", infy, 60, [sum(price.values[: i + 1]) / (i + 1) for i in range(n)])

    checks = []
    for t in (15 * 60, 20 * 60, 30 * 60):
        c = price.at(t)
        for m, back in ((1, 60), (5, 300), (15, 900)):
            checks.append(Check("stock:return_%dm:percent" % m, infy, t, (c / price.at(t - back) - 1) * 100))
        checks.append(Check("stock:gap_open:percent", infy, t, (opn.at(t) - pc.at(t)) / pc.at(t) * 100))
        checks.append(Check("stock:vwap_deviation:percent", infy, t, (c - vwap.at(t)) / vwap.at(t) * 100))
    return ["stock_recording.rules.yml"], [
        test_case("base returns, gap and VWAP deviation match the reference", 60, [price, opn, pc, vwap], checks)
    ]


# --- multi-session timeline (30m slots) -------------------------------------------------------

SLOT = 1800
SLOTS_PER_DAY = 48
PRE_OPEN_SLOT, FIRST_OPEN_SLOT, LAST_OPEN_SLOT, POST_CLOSE_SLOT = 18, 19, 30, 31  # 09:00 .. 15:30


class Calendar:
    """`days` days of 30m slots; holidays have no pre_open/open/post_close phase."""

    def __init__(self, days, holidays=()):
        self.days, self.holidays = days, set(holidays)
        self.n = days * SLOTS_PER_DAY

    def trading(self, d):
        return d not in self.holidays

    def t(self, d, slot):
        return (d * SLOTS_PER_DAY + slot) * SLOT

    def _flags(self, pred):
        return [1 if self.trading(i // SLOTS_PER_DAY) and pred(i % SLOTS_PER_DAY) else 0 for i in range(self.n)]

    def series(self):
        phase = lambda p: dict(CORE, phase=p)
        is_open = lambda s: FIRST_OPEN_SLOT <= s <= LAST_OPEN_SLOT
        open_flags = self._flags(is_open)
        stc = [(POST_CLOSE_SLOT - i % SLOTS_PER_DAY) * SLOT if f else 0 for i, f in enumerate(open_flags)]
        return [
            Series("stock_market_phase", phase("pre_open"), SLOT, self._flags(lambda s: s == PRE_OPEN_SLOT), "%d"),
            Series("stock_market_phase", phase("open"), SLOT, open_flags, "%d"),
            Series("stock_market_phase", phase("post_close"), SLOT, self._flags(lambda s: s == POST_CLOSE_SLOT), "%d"),
            Series("stock_market_open", CORE, SLOT, open_flags, "%d"),
            Series("stock_market_seconds_to_close", CORE, SLOT, stc, "%d"),
        ]

    def daily(self, values):
        """Expand one value per day into a 30m series (the exporter keeps the last state)."""
        return [values[i // SLOTS_PER_DAY] for i in range(self.n)]


def daily_bars(seed, days, start=100.0):
    """Per-day (PC, H, L) with PC = previous day's close."""
    rnd = random.Random(seed)
    close, out = start, []
    for _ in range(days):
        pc = close
        close = round(pc * math.exp(rnd.gauss(0, 0.015)), 2)
        h = round(max(pc, close) * (1 + rnd.uniform(0, 0.01)), 2)
        lo = round(min(pc, close) * (1 - rnd.uniform(0, 0.01)), 2)
        if rnd.random() < 0.2:  # gap day: PC outside today's range
            h, lo = round(pc * 1.03, 2), round(pc * 1.015, 2)
        out.append((pc, h, lo))
    return out


def previous_session(cal, d):
    """Last trading day before d within 7 days, or None."""
    for p in range(d - 1, max(d - 8, -1), -1):
        if cal.trading(p) and cal.t(d, FIRST_OPEN_SLOT + 1) - cal.t(p, POST_CLOSE_SLOT) < 7 * 86400:
            return p
    return None


# --- nse_price_levels.rules.yml ---------------------------------------------------------------


def family_price_levels():
    infy = instrument("INFY")
    cases = []

    # Intraday return on 1m data.
    n = 31
    price = Series("stock_last_price", infy, 60, random_walk(2, n))
    opn = Series("stock_open_price", infy, 60, constant(99.75, n))
    checks = [Check("stock:intraday_return:percent", infy, t, (price.at(t) - opn.at(t)) / opn.at(t) * 100) for t in (60, 600, 1800)]
    cases.append(test_case("intraday return matches the reference", 60, [price, opn], checks))
    return ["nse_price_levels.rules.yml"], cases


def family_pivots():
    infy = instrument("INFY")
    cases = []
    # Floor pivots over 4 sessions with a holiday on day 2.
    cal = Calendar(4, holidays=[2])
    bars = daily_bars(3, cal.days)
    pc = Series("stock_previous_close_price", infy, SLOT, cal.daily([b[0] for b in bars]))
    hi = Series("stock_high_price", infy, SLOT, cal.daily([b[1] for b in bars]))
    lo = Series("stock_low_price", infy, SLOT, cal.daily([b[2] for b in bars]))
    checks = []
    for d in range(cal.days):
        p = previous_session(cal, d)
        for slot in (PRE_OPEN_SLOT, FIRST_OPEN_SLOT + 1, LAST_OPEN_SLOT):
            t = cal.t(d, slot)
            if p is None or not cal.trading(d):
                checks.append(Absent("stock:pivot:price", dict(infy, level="P"), t))
                continue
            ph, pl, c = bars[p][1], bars[p][2], pc.at(t)
            pp = (ph + pl + c) / 3
            for level, v in (("P", pp), ("R1", 2 * pp - pl), ("S1", 2 * pp - ph), ("R2", pp + (ph - pl)), ("S2", pp - (ph - pl))):
                checks.append(Check("stock:pivot:price", dict(infy, level=level), t, v))
        # Not published outside pre_open/open.
        checks.append(Absent("stock:pivot:price", dict(infy, level="P"), cal.t(d, POST_CLOSE_SLOT)))
    cases.append(test_case("floor pivots from the previous session's snapshot", SLOT, cal.series() + [pc, hi, lo], checks))

    # promtool evaluates every group at evaluation_interval; 30m matches the EOD group in production.
    return ["nse_eod_snapshot.rules.yml", "nse_price_levels.rules.yml"], cases, SLOT


# --- nse_momentum.rules.yml + nse_trend.rules.yml ---------------------------------------------


def mean(xs):
    return sum(xs) / len(xs)


def rsi(price, t, n=14):
    pts = range((int((t - n * 60) // 60) + 1) * 60, int(t) + 1, 60)
    gains = [max(price.at(k) - price.at(k - 60), 0) for k in pts]
    losses = [max(price.at(k - 60) - price.at(k), 0) for k in pts]
    if mean(losses) == 0:
        return 100.0
    return 100 - 100 / (1 + mean(gains) / mean(losses))


def stochastic_k(price, t, rng=840):
    xs = [v for _, v in price.samples(t - rng, t)]
    return (price.at(t) - min(xs)) / (max(xs) - min(xs)) * 100


def family_momentum():
    step, n = 15, 4 * 41  # 15s samples for 41 minutes
    cases = []
    series, checks = [], []
    for seed, sym in ((4, "INFY"), (5, "TCS")):
        lbl = instrument(sym)
        price = Series("stock_last_price", lbl, step, random_walk(seed, n, sigma=0.002))
        series.append(price)
        for t in (15 * 60, 20 * 60, 26 * 60, 33 * 60, 40 * 60):
            checks.append(Check("stock:rsi_14m:index", lbl, t, rsi(price, t)))
            checks.append(Check("stock:stochastic_k_14m:percent", lbl, t, stochastic_k(price, t)))
            if t >= 26 * 60:
                macd = mean(price.bars(t, 12 * 60)) - mean(price.bars(t, 26 * 60))
                checks.append(Check("stock:macd_12_26m:price", lbl, t, macd))
    cases.append(test_case("RSI, Stochastic %K and MACD match the reference on 15s data", step, series, checks))
    return ["nse_momentum.rules.yml", "nse_trend.rules.yml"], cases


# --- nse_volatility.rules.yml -----------------------------------------------------------------


def pstdev(xs):
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / len(xs))


ANNUALISE = math.sqrt(375 * 252)


def realized_vol(price, t):
    """stddev_over_time(stock:return_1m:percent[15m]) with return_1m recorded every 5s."""
    rets = []
    for s in range(int(t) - 895, int(t) + 1, 5):
        c, p = price.at(s), price.at(s - 60) if s >= 60 else None
        if c is not None and p is not None:
            rets.append((c / p - 1) * 100)
    return pstdev(rets) * ANNUALISE


def family_volatility():
    step, n = 15, 4 * 41
    series, checks = [], []
    for seed, sym in ((6, "INFY"), (7, "TCS")):
        lbl = instrument(sym)
        price = Series("stock_last_price", lbl, step, random_walk(seed, n, sigma=0.002))
        series.append(price)
        for t in (20 * 60, 30 * 60, 40 * 60):
            bars = price.bars(t, 20 * 60)
            mid, sd = mean(bars), pstdev(bars)
            checks.append(Check("stock:bollinger_width_20m:percent", lbl, t, 4 * sd / mid * 100))
            checks.append(Check("stock:bollinger_percent_b_20m:ratio", lbl, t, (price.at(t) - mid + 2 * sd) / (4 * sd)))
            checks.append(Check("stock:realized_vol_annualised:percent", lbl, t, realized_vol(price, t), rel_tol=1e-8))
    return ["stock_recording.rules.yml", "nse_volatility.rules.yml"], [
        test_case("Bollinger width, %B and realized volatility match the reference", step, series, checks)
    ], 5


def true_range(pc, h, lo):
    return max(h, pc) - min(lo, pc)


def family_atr():
    infy = instrument("INFY")
    cal = Calendar(26, holidays=[5, 6, 12, 13, 19, 20])  # weekends
    bars = daily_bars(8, cal.days)
    pc = Series("stock_previous_close_price", infy, SLOT, cal.daily([b[0] for b in bars]))
    hi = Series("stock_high_price", infy, SLOT, cal.daily([b[1] for b in bars]))
    lo = Series("stock_low_price", infy, SLOT, cal.daily([b[2] for b in bars]))
    checks = []
    for d in range(cal.days):
        t = cal.t(d, FIRST_OPEN_SLOT + 1)
        trs = [
            true_range(*bars[p])
            for p in range(d)
            if cal.trading(p) and t - 20 * 86400 < cal.t(p, POST_CLOSE_SLOT) <= t
        ]
        if len(trs) < 10:
            checks.append(Absent("stock:atr_14d:points", infy, t))
            checks.append(Absent("stock:range_expansion:ratio", infy, t))
            continue
        atr = mean(trs)
        checks.append(Check("stock:atr_14d:points", infy, t, atr))
        checks.append(Check("stock:range_expansion:ratio", infy, t, (bars[d][1] - bars[d][2]) / atr))
    return ["nse_eod_snapshot.rules.yml", "nse_volatility.rules.yml"], [
        test_case("ATR(14) and range expansion over 26 days with weekends", SLOT, cal.series() + [pc, hi, lo], checks)
    ], SLOT


# --- nse_volume_liquidity.rules.yml ----------------------------------------------------------


def family_rvol():
    infy = instrument("INFY")
    cal = Calendar(20, holidays=[5, 6, 12, 13])
    rnd = random.Random(9)
    finals = [rnd.randint(500_000, 2_000_000) for _ in range(cal.days)]

    def day_volume(i):
        d, s = divmod(i, SLOTS_PER_DAY)
        if not cal.trading(d):
            return finals[d - 1] if d else 0
        return round(finals[d] * min(1.0, max(0.0, (s - PRE_OPEN_SLOT) / (POST_CLOSE_SLOT - PRE_OPEN_SLOT))))

    vol = Series("stock_day_volume_shares", infy, SLOT, [day_volume(i) for i in range(cal.n)], "%d")
    stc = cal.series()[4]
    checks = []
    for d in range(cal.days):
        for slot in (FIRST_OPEN_SLOT, FIRST_OPEN_SLOT + 1, LAST_OPEN_SLOT):
            t = cal.t(d, slot)
            sessions = [
                finals[p] for p in range(d) if cal.trading(p) and t - 14 * 86400 < cal.t(p, POST_CLOSE_SLOT) <= t
            ]
            elapsed = (22500 - stc.at(t)) / 22500
            if not cal.trading(d) or len(sessions) < 5 or stc.at(t) >= 20700:
                checks.append(Absent("stock:relative_volume:ratio", infy, t))
                continue
            checks.append(Check("stock:relative_volume:ratio", infy, t, vol.at(t) / (mean(sessions) * elapsed)))
    return ["nse_eod_snapshot.rules.yml", "nse_volume_liquidity.rules.yml"], [
        test_case("relative volume vs the 14-day session average, after 09:45 only", SLOT, cal.series() + [vol], checks)
    ], SLOT


# --- nse_order_flow.rules.yml ----------------------------------------------------------------


def sgn(x):
    return (x > 0) - (x < 0)


def family_order_flow():
    step, n = 15, 4 * 80  # 80 minutes of 15s samples
    series, checks = [], []
    for seed, sym in ((10, "INFY"), (11, "TCS")):
        lbl = instrument(sym)
        rnd = random.Random(seed)
        bias = 0.3 if sym == "INFY" else -0.2
        rets = [0.0 if rnd.random() < 0.1 else rnd.gauss(bias * 0.05, 0.05) for _ in range(n)]
        vols = [rnd.randint(0, 5000) for _ in range(n)]
        ret = Series("stock:return_1m:percent", lbl, step, rets, "%.4f")
        vol = Series("stock:volume_1m:shares", lbl, step, vols, "%d")
        series += [ret, vol]
        for t in (30 * 60, 60 * 60, 75 * 60):
            pts = [k for k in range((int((t - 3600) // 60) + 1) * 60, t + 1, 60) if k >= 0]
            num = sum(vol.at(k) * sgn(ret.at(k)) for k in pts)
            den = sum(vol.at(k) for k in pts)
            checks.append(Check("stock:volume_delta_1h:ratio", lbl, t, num / den))
    return ["nse_order_flow.rules.yml"], [
        test_case("tick-rule volume delta over 1h of 1m bars", step, series, checks)
    ]


# --- nse_market_breadth.rules.yml ------------------------------------------------------------


def family_breadth():
    rnd = random.Random(12)
    n, step = 11, 60
    sectors = ["IT", "Financial Services", "Energy"]
    names = [("C%02d" % i, sectors[i % 3], "core") for i in range(12)] + [("B%02d" % i, "unknown", "broad") for i in range(6)]
    series, inst = [], []
    for sym, sec, tier in names:
        lbl = instrument(sym, sector=sec, tier=tier)
        pc = rnd.uniform(100, 2000)
        chg = [rnd.gauss(0, 1.5) if rnd.random() > 0.05 else 0.0 for _ in range(n)]
        ltp = [round(pc * (1 + c / 100), 2) for c in chg]
        vwap = [round(p * (1 + rnd.gauss(0, 0.004)), 2) for p in ltp]
        vol = [rnd.randint(10_000, 5_000_000) for _ in range(n)]
        up = [round(pc * 1.05, 2) if rnd.random() > 0.15 else round(p, 2) for p in ltp]
        lo = [round(pc * 0.95, 2) if rnd.random() > 0.1 else round(p, 2) for p in ltp]
        s = {
            "chg": Series("stock_change_percent", lbl, step, chg, "%.4f"),
            "ltp": Series("stock_last_price", lbl, step, ltp),
            "vwap": Series("stock_average_traded_price", lbl, step, vwap),
            "vol": Series("stock_day_volume_shares", lbl, step, vol, "%d"),
            "up": Series("stock_circuit_upper_limit_price", lbl, step, up),
            "lo": Series("stock_circuit_lower_limit_price", lbl, step, lo),
        }
        series += list(s.values())
        inst.append((sec, tier, s))
    nifty = Series(
        "stock_change_percent", instrument("NIFTY 50", sector="Index", itype="INDEX"), step,
        [rnd.gauss(0, 0.8) for _ in range(n)], "%.4f",
    )
    series.append(nifty)

    checks = []
    for t in (0, 5 * 60, 10 * 60):
        v = lambda s, k: s[k].at(t)
        above = sum(1 for _, _, s in inst if v(s, "ltp") > v(s, "vwap"))
        checks.append(Check("market:above_vwap:ratio", {}, t, above / len(inst)))
        adv = [s for _, _, s in inst if v(s, "chg") > 0]
        dec = [s for _, _, s in inst if v(s, "chg") < 0]
        trin = (len(adv) / len(dec)) / (sum(v(s, "vol") for s in adv) / sum(v(s, "vol") for s in dec))
        checks.append(Check("market:trin:ratio", {}, t, trin))
        core = [v(s, "chg") for _, tier, s in inst if tier == "core"]
        checks.append(Check("market:dispersion:percent", {}, t, pstdev(core)))
        hits_up = sum(1 for _, _, s in inst if v(s, "ltp") >= v(s, "up"))
        hits_lo = sum(1 for _, _, s in inst if v(s, "ltp") <= v(s, "lo"))
        checks.append(Check("market:circuit_hits:count", {"band": "upper"}, t, hits_up))
        checks.append(Check("market:circuit_hits:count", {"band": "lower"}, t, hits_lo))
        for sec in sectors:
            avg = mean([v(s, "chg") for ssec, tier, s in inst if ssec == sec and tier == "core"])
            checks.append(Check("sector:relative_strength:percent", {"sector": sec}, t, avg - nifty.at(t)))
    return ["nse_market_breadth.rules.yml"], [
        test_case("breadth, TRIN, dispersion, circuit hits and sector RS match the reference", step, series, checks)
    ]


FAMILIES = {
    "base": family_base,
    "price_levels": family_price_levels,
    "pivots": family_pivots,
    "momentum": family_momentum,
    "volatility": family_volatility,
    "atr": family_atr,
    "rvol": family_rvol,
    "order_flow": family_order_flow,
    "breadth": family_breadth,
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=TESTS_DIR)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    for family, gen in FAMILIES.items():
        rule_files, cases, *rest = gen()
        eval_interval = rest[0] if rest else 15
        path = os.path.join(args.out, "reference_%s_test.yml" % family)
        with open(path, "w") as f:
            f.write(render(family, rule_files, cases, eval_interval))


if __name__ == "__main__":
    main()
