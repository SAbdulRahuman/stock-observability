#!/usr/bin/env python3
"""Reference implementation of the NSE KPI formulas (stdlib only).

Generates promtool unit tests (prometheus/tests/reference_<family>_test.yml) whose expected
values are computed here from textbook definitions, independently of the PromQL rules.
Each check asserts |rule - reference| <= tol with `abs(rule - E) <= bool tol`, so the file
needs no fuzzy compare and failures show up as value 0.

    python3 prometheus/tests/reference/kpiref.py            # rewrite the test files
    python3 prometheus/tests/reference/kpiref.py --out DIR  # write elsewhere (make check-reference)
"""

import argparse
import math
import os
import random

LOOKBACK = 300  # Prometheus default lookback delta, seconds
REL_TOL = 1e-9  # proposal §A12: exact KPIs within 1e-9 relative
ABS_TOL = 1e-9

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS_DIR = os.path.dirname(HERE)

# promtool evaluates groups in random order unless told; reference values assume inputs first.
GROUP_ORDER = {
    "volatility": ["stock_fast", "stock_slow", "portfolio", "nse_volatility", "nse_volatility_r2", "nse_volatility_alerts"],
    "atr": ["nse_eod_snapshot", "nse_volatility", "nse_volatility_r2", "nse_volatility_alerts"],
    "osc": ["nse_bars", "nse_momentum", "nse_momentum_wilder", "nse_momentum_bars", "nse_momentum_alerts"],
    "ma": ["stock_fast", "stock_slow", "portfolio", "nse_trend", "nse_trend_regression", "nse_trend_alerts", "nse_moving_averages"],
}

CORE = {"job": "stock_core", "instance": "se"}
BROAD = {"job": "stock_broad", "instance": "se"}


def instrument(symbol, sector="IT", itype="EQ", tier="core"):
    base = CORE if tier == "core" else BROAD
    return dict(base, exchange="NSE", symbol=symbol, sector=sector, instrument_type=itype, tier=tier)


class Series:
    """A promtool input series: samples at i * step seconds, None = no sample."""

    def __init__(self, metric, labels, step, values, fmt="%.2f"):
        self.metric = metric
        self.labels = labels
        self.step = step
        # Round-trip through the text form so the reference sees exactly what promtool loads.
        self.text = [("_" if v is None else fmt % v) for v in values]
        self.values = [None if s == "_" else float(s) for s in self.text]

    def at(self, t):
        """Instant value at t: newest sample in (t - lookback, t]."""
        i = min(int(t // self.step), len(self.values) - 1)
        while i >= 0 and i * self.step > t - LOOKBACK:
            if self.values[i] is not None:
                return self.values[i]
            i -= 1
        return None

    def samples(self, start, end):
        """Raw samples with timestamps in (start, end]."""
        return [
            (i * self.step, v)
            for i, v in enumerate(self.values)
            if v is not None and start < i * self.step <= end
        ]

    def bars(self, t, rng, res=60):
        """Subquery points of `x[rng:res]` at t: x at every multiple of res in (t - rng, t]."""
        first = (int((t - rng) // res) + 1) * res
        return [self.at(ts) for ts in range(first, int(t) + 1, res)]


def selector(metric, labels):
    return metric + "{" + ",".join('%s="%s"' % (k, v) for k, v in labels.items()) + "}"


def duration(seconds):
    seconds = int(seconds)
    if seconds % 86400 == 0:
        return "%dd" % (seconds // 86400)
    if seconds % 3600 == 0:
        return "%dh" % (seconds // 3600)
    if seconds % 60 == 0:
        return "%dm" % (seconds // 60)
    return "%ds" % seconds


class Check:
    def __init__(self, metric, labels, t, expected, rel_tol=REL_TOL, abs_tol=ABS_TOL):
        self.metric, self.labels, self.t, self.expected = metric, labels, t, expected
        self.tol = max(rel_tol * abs(expected), abs_tol)


class Absent:
    """Asserts that `metric{labels}` has no sample at t."""

    def __init__(self, metric, labels, t):
        self.metric, self.labels, self.t = metric, labels, t


def test_case(name, step, series, checks):
    return {"name": name, "step": step, "series": series, "checks": checks}


def render(family, rule_files, cases, eval_interval):
    out = [
        "# Generated by prometheus/tests/reference/kpiref.py (family %s). DO NOT EDIT." % family,
        "rule_files:",
    ]
    out += ["  - ../rules/%s" % f for f in rule_files]
    out += ["", "evaluation_interval: %s" % duration(eval_interval)]
    if family in GROUP_ORDER:
        out += ["", "group_eval_order:"] + ["  - %s" % g for g in GROUP_ORDER[family]]
    out += ["", "tests:"]
    for c in cases:
        out.append("  - name: %s" % c["name"])
        out.append("    interval: %s" % duration(c["step"]))
        out.append("    input_series:")
        for s in c["series"]:
            out.append("      - series: '%s'" % selector(s.metric, s.labels))
            out.append("        values: '%s'" % " ".join(s.text))
        out.append("    promql_expr_test:")
        for ck in c["checks"]:
            sel = selector(ck.metric, ck.labels)
            out.append("      - eval_time: %s" % duration(ck.t))
            if isinstance(ck, Absent):
                out.append("        expr: '%s'" % sel)
                out.append("        exp_samples: []")
                continue
            out.append("        expr: 'abs(%s - (%r)) <= bool %r'" % (sel, ck.expected, ck.tol))
            out.append("        exp_samples:")
            out.append("          - labels: '%s'" % selector("", ck.labels))
            out.append("            value: 1")
    return "\n".join(out) + "\n"


# --- deterministic input data ----------------------------------------------------------------


def random_walk(seed, n, start=100.0, sigma=0.004, tick=0.05):
    rnd = random.Random(seed)
    p, out = start, []
    for _ in range(n):
        p *= math.exp(rnd.gauss(0, sigma))
        out.append(round(round(p / tick) * tick, 2))
    return out


def constant(v, n):
    return [v] * n


# --- base rules (stock_recording.rules.yml) -----------------------------------------------------


def family_base():
    n = 31  # 30 minutes of 1m samples
    infy = instrument("INFY")
    price = Series("stock_last_price", infy, 60, random_walk(1, n))
    opn = Series("stock_open_price", infy, 60, constant(price.values[0], n))
    pc = Series("stock_previous_close_price", infy, 60, constant(98.4, n))
    vwap = Series("stock_average_traded_price", infy, 60, [sum(price.values[: i + 1]) / (i + 1) for i in range(n)])

    checks = []
    for t in (15 * 60, 20 * 60, 30 * 60):
        c = price.at(t)
        for m, back in ((1, 60), (5, 300), (15, 900)):
            checks.append(Check("stock:return_%dm:percent" % m, infy, t, (c / price.at(t - back) - 1) * 100))
        checks.append(Check("stock:gap_open:percent", infy, t, (opn.at(t) - pc.at(t)) / pc.at(t) * 100))
        checks.append(Check("stock:vwap_deviation:percent", infy, t, (c - vwap.at(t)) / vwap.at(t) * 100))
    return ["stock_recording.rules.yml"], [
        test_case("base returns, gap and VWAP deviation match the reference", 60, [price, opn, pc, vwap], checks)
    ]


# --- multi-session timeline (30m slots) -------------------------------------------------------

SLOT = 1800
SLOTS_PER_DAY = 48
PRE_OPEN_SLOT, FIRST_OPEN_SLOT, LAST_OPEN_SLOT, POST_CLOSE_SLOT = 18, 19, 30, 31  # 09:00 .. 15:30


class Calendar:
    """`days` days of 30m slots; holidays have no pre_open/open/post_close phase."""

    def __init__(self, days, holidays=()):
        self.days, self.holidays = days, set(holidays)
        self.n = days * SLOTS_PER_DAY

    def trading(self, d):
        return d not in self.holidays

    def t(self, d, slot):
        return (d * SLOTS_PER_DAY + slot) * SLOT

    def _flags(self, pred):
        return [1 if self.trading(i // SLOTS_PER_DAY) and pred(i % SLOTS_PER_DAY) else 0 for i in range(self.n)]

    def series(self):
        phase = lambda p: dict(CORE, phase=p)
        is_open = lambda s: FIRST_OPEN_SLOT <= s <= LAST_OPEN_SLOT
        open_flags = self._flags(is_open)
        stc = [(POST_CLOSE_SLOT - i % SLOTS_PER_DAY) * SLOT if f else 0 for i, f in enumerate(open_flags)]
        return [
            Series("stock_market_phase", phase("pre_open"), SLOT, self._flags(lambda s: s == PRE_OPEN_SLOT), "%d"),
            Series("stock_market_phase", phase("open"), SLOT, open_flags, "%d"),
            Series("stock_market_phase", phase("post_close"), SLOT, self._flags(lambda s: s == POST_CLOSE_SLOT), "%d"),
            Series("stock_market_open", CORE, SLOT, open_flags, "%d"),
            Series("stock_market_seconds_to_close", CORE, SLOT, stc, "%d"),
        ]

    def daily(self, values):
        """Expand one value per day into a 30m series (the exporter keeps the last state)."""
        return [values[i // SLOTS_PER_DAY] for i in range(self.n)]


def daily_bars(seed, days, start=100.0):
    """Per-day (PC, H, L) with PC = previous day's close."""
    rnd = random.Random(seed)
    close, out = start, []
    for _ in range(days):
        pc = close
        close = round(pc * math.exp(rnd.gauss(0, 0.015)), 2)
        h = round(max(pc, close) * (1 + rnd.uniform(0, 0.01)), 2)
        lo = round(min(pc, close) * (1 - rnd.uniform(0, 0.01)), 2)
        if rnd.random() < 0.2:  # gap day: PC outside today's range
            h, lo = round(pc * 1.03, 2), round(pc * 1.015, 2)
        out.append((pc, h, lo))
    return out


def previous_session(cal, d):
    """Last trading day before d within 7 days, or None."""
    for p in range(d - 1, max(d - 8, -1), -1):
        if cal.trading(p) and cal.t(d, FIRST_OPEN_SLOT + 1) - cal.t(p, POST_CLOSE_SLOT) < 7 * 86400:
            return p
    return None


