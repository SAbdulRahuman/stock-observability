def running(values, fn):
    out, cur = [], None
    for v in values:
        cur = v if cur is None else fn(cur, v)
        out.append(cur)
    return out


def family_bars():
    step, minutes = 15, 75
    n = 4 * minutes + 1
    series = [Series("stock_market_open", CORE, step, constant(1, n), "%d")]
    checks = []
    rnd = random.Random(15)
    vols = []
    for i in range(n):  # day volume resets to a small value at minute 30 (new session)
        vols.append(rnd.randint(0, 400) if i == 120 else (vols[-1] if vols else 0) + rnd.randint(0, 900))
    for sym, prices in (("INFY", random_walk(16, n, sigma=0.002)), ("FLAT", constant(250.0, n))):
        lbl = instrument(sym)
        price = Series("stock_last_price", lbl, step, prices)
        hi = Series("stock_high_price", lbl, step, running(price.values, max))
        lo = Series("stock_low_price", lbl, step, running(price.values, min))
        vol = Series("stock_day_volume_shares", lbl, step, vols, "%d")
        series += [price, hi, lo, vol]
        for t in (60, 600, 1800, 1860, 2700, 3600, 3660, 4500):
            window = [v for _, v in price.samples(t - 60, t)]
            h, l, c = max(window), min(window), price.at(t)
            dv = vol.at(t) - vol.at(t - 60)
            v = dv if dv >= 0 else vol.at(t)
            mfv = ((c - l) - (h - c)) / (h - l) * v if h > l else 0.0
            checks += [
                Check("stock:bar_1m_high:price", lbl, t, h),
                Check("stock:bar_1m_low:price", lbl, t, l),
                Check("stock:bar_1m_close:price", lbl, t, c),
                Check("stock:bar_1m_volume:shares", lbl, t, v),
                Check("stock:bar_1m_typical:price", lbl, t, (h + l + c) / 3),
                Check("stock:bar_1m_money_flow_volume:shares", lbl, t, mfv, abs_tol=1e-6),
                Check("stock:log_return_1m:ratio", lbl, t, math.log(c / price.at(t - 60)), abs_tol=1e-12),
                Check("stock:day_range:percent", lbl, t, (hi.at(t) - lo.at(t)) / lo.at(t) * 100),
            ]
            if hi.at(t) > lo.at(t):
                checks.append(Check("stock:range_position:ratio", lbl, t, (c - lo.at(t)) / (hi.at(t) - lo.at(t))))
            else:
                checks.append(Absent("stock:range_position:ratio", lbl, t))
            if t >= 3600:
                checks.append(Check("stock:return_60m:percent", lbl, t, (c / price.at(t - 3600) - 1) * 100, abs_tol=1e-9))
            else:
                checks.append(Absent("stock:return_60m:percent", lbl, t))
    return ["nse_bars.rules.yml", "nse_returns.rules.yml"], [
        test_case("1m bars (incl. a day-volume reset) and returns match the reference", step, series, checks)
    ], 60


def family_osc():
    """Momentum, %D and the bar oscillators (CCI, MFI, Awesome); bars from t=0, 1m evaluations."""
    step, minutes = 15, 50
    n = 4 * minutes + 1
    series = [
        Series("stock_market_open", CORE, step, constant(1, n), "%d"),
        Series("stock_market_seconds_to_close", CORE, step, [22500 - i * step for i in range(n)], "%d"),
    ]
    checks = []
    rnd = random.Random(20)
    vols = running([rnd.randint(0, 900) for _ in range(n)], lambda a, b: a + b)
    minutes_t = list(range(0, minutes * 60 + 1, 60))
    for seed, sym in ((21, "INFY"), (22, "TCS")):
        lbl = instrument(sym)
        price = Series("stock_last_price", lbl, step, random_walk(seed, n, sigma=0.002))
        vol = Series("stock_day_volume_shares", lbl, step, vols, "%d")
        series += [price, vol]
        hi, lo, tp, bv = {}, {}, {}, {}
        for k in minutes_t:
            w = [v for _, v in price.samples(k - 60, k)]
            hi[k], lo[k] = max(w), min(w)
            tp[k] = (hi[k] + lo[k] + price.at(k)) / 3
            bv[k] = vol.at(k) - vol.at(k - 60) if k >= 60 else vol.at(k)
        within = lambda d, t, rng: [d[k] for k in minutes_t if t - rng < k <= t]
        for t in (5 * 60, 15 * 60, 20 * 60, 25 * 60, 34 * 60, 40 * 60, 50 * 60):
            if t >= 600:
                checks.append(Check("stock:momentum_10m:points", lbl, t, price.at(t) - price.at(t - 600), abs_tol=1e-9))
            checks.append(Check("stock:stochastic_d_3m:percent", lbl, t,
                                mean([stochastic_k(price, k) for k in (t - 120, t - 60, t)]), rel_tol=1e-8))
            if t >= 19 * 60:
                sma_tp = lambda k: mean(within(tp, k, 1200))
                md = mean([abs(tp[k] - sma_tp(k)) for k in minutes_t if t - 1200 < k <= t])
                checks.append(Check("stock:cci_20m:index", lbl, t, (tp[t] - sma_tp(t)) / (0.015 * md), rel_tol=1e-7))
            else:
                checks.append(Absent("stock:cci_20m:index", lbl, t))
            if t >= 14 * 60:
                pts = [k for k in minutes_t if t - 840 < k <= t and k >= 60]
                pos = sum(tp[k] * bv[k] for k in pts if tp[k] > tp[k - 60])
                neg = sum(tp[k] * bv[k] for k in pts if tp[k] < tp[k - 60])
                checks.append(Check("stock:mfi_14m:index", lbl, t, 100 - 100 / (1 + pos / neg), rel_tol=1e-8))
            else:
                checks.append(Absent("stock:mfi_14m:index", lbl, t))
            if t >= 33 * 60:
                ao = (mean(within(hi, t, 300)) + mean(within(lo, t, 300))) / 2 - (mean(within(hi, t, 2040)) + mean(within(lo, t, 2040))) / 2
                checks.append(Check("stock:awesome_oscillator:price", lbl, t, ao, abs_tol=1e-9))
            else:
                checks.append(Absent("stock:awesome_oscillator:price", lbl, t))
    return ["nse_bars.rules.yml", "nse_momentum.rules.yml"], [
        test_case("momentum, %D, CCI, MFI and Awesome oscillator match the reference", step, series, checks)
    ], 60


