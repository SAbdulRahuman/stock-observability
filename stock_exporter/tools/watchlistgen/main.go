// Command watchlistgen builds a watchlist from an NSE index constituent CSV
// (e.g. https://archives.nseindia.com/content/indices/ind_nifty200list.csv).
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/seenimo/stock_exporter/internal/watchlist"
)

// Kite trading symbols of NSE/BSE indices; unresolvable ones are logged by the exporter and skipped.
var indices = []watchlist.Entry{
	{Exchange: "NSE", Symbol: "NIFTY 50"},
	{Exchange: "NSE", Symbol: "NIFTY NEXT 50"},
	{Exchange: "NSE", Symbol: "NIFTY 100"},
	{Exchange: "NSE", Symbol: "NIFTY 200"},
	{Exchange: "NSE", Symbol: "NIFTY 500"},
	{Exchange: "NSE", Symbol: "NIFTY MIDCAP 100"},
	{Exchange: "NSE", Symbol: "NIFTY BANK"},
	{Exchange: "NSE", Symbol: "NIFTY FIN SERVICE"},
	{Exchange: "NSE", Symbol: "NIFTY IT"},
	{Exchange: "NSE", Symbol: "NIFTY AUTO"},
	{Exchange: "NSE", Symbol: "NIFTY PHARMA"},
	{Exchange: "NSE", Symbol: "NIFTY FMCG"},
	{Exchange: "NSE", Symbol: "NIFTY METAL"},
	{Exchange: "NSE", Symbol: "NIFTY ENERGY"},
	{Exchange: "NSE", Symbol: "NIFTY REALTY"},
	{Exchange: "NSE", Symbol: "NIFTY PSU BANK"},
	{Exchange: "NSE", Symbol: "NIFTY MEDIA"},
	{Exchange: "NSE", Symbol: "INDIA VIX"},
	{Exchange: "BSE", Symbol: "SENSEX"},
}

func main() {
	var (
		in       = flag.String("constituents", "", "NSE index constituent CSV (Company Name,Industry,Symbol,Series,ISIN Code).")
		out      = flag.String("out", "-", "Output file, - for stdout.")
		universe = flag.Bool("all-nse", true, "Add all NSE equity symbols as the broad tier.")
	)
	flag.Parse()
	if *in == "" {
		fmt.Fprintln(os.Stderr, "-constituents is required")
		os.Exit(2)
	}
	if err := run(*in, *out, *universe); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(in, out string, allNSE bool) error {
	f, err := os.Open(in)
	if err != nil {
		return err
	}
	defer f.Close()
	entries, err := parseConstituents(f)
	if err != nil {
		return err
	}
	w := watchlist.Watchlist{}
	for _, e := range indices {
		e.Type = "INDEX"
		e.Sector = "Index"
		w.Instruments = append(w.Instruments, e)
	}
	w.Instruments = append(w.Instruments, entries...)
	if allNSE {
		w.Universes = []watchlist.Universe{{Exchange: "NSE", Segment: "NSE", InstrumentTypes: []string{"EQ"}, ExcludeHyphenated: true}}
	}
	b, err := yaml.Marshal(w)
	if err != nil {
		return err
	}
	if _, err := watchlist.Parse(b); err != nil {
		return fmt.Errorf("generated watchlist is invalid: %w", err)
	}
	header := fmt.Sprintf("# Generated by tools/watchlistgen from %s. Core tier: indices + index constituents.\n", filepath.Base(in))
	if allNSE {
		header += "# Broad tier: every NSE EQ symbol (scraped less frequently).\n"
	}
	b = append([]byte(header), b...)
	if out == "-" {
		_, err = os.Stdout.Write(b)
		return err
	}
	return os.WriteFile(out, b, 0o644)
}

func parseConstituents(r io.Reader) ([]watchlist.Entry, error) {
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		return nil, err
	}
	if len(rows) < 2 {
		return nil, fmt.Errorf("no constituents")
	}
	col := map[string]int{}
	for i, h := range rows[0] {
		col[strings.TrimSpace(h)] = i
	}
	sym, okS := col["Symbol"]
	ind, okI := col["Industry"]
	if !okS || !okI {
		return nil, fmt.Errorf("CSV must have Symbol and Industry columns, got %v", rows[0])
	}
	var out []watchlist.Entry
	for _, r := range rows[1:] {
		out = append(out, watchlist.Entry{Exchange: "NSE", Symbol: strings.TrimSpace(r[sym]), Sector: strings.TrimSpace(r[ind])})
	}
	return out, nil
}
